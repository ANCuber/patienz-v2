"""Per-image annotation (tools/enrich_image_bank.py).

What is pinned: the PTB-XL fields that were previously dropped become part of
the film's claim (validated co-findings, stadium, axis); the review sidecars
merge without overwriting a human's decision; a chest film's side is recorded
only when the readers agree with each other and with the radiologist's box,
and always as provisional.
"""
import json
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import enrich_image_bank as en  # noqa: E402
from util import image_bank as ib  # noqa: E402

SCP = ("﻿,description,diagnostic,form,rhythm,diagnostic_class,diagnostic_subclass\n"
       "IMI,inferior myocardial infarction,1.0,,,MI,IMI\n"
       "ASMI,anteroseptal myocardial infarction,1.0,,,MI,AMI\n"
       "LAFB,left anterior fascicular block,1.0,,,CD,LAFB/LPFB\n"
       "ABQRS,abnormal QRS,,1.0,,,\n"
       "SR,sinus rhythm,,,1.0,,\n")
DB_HEADER = ("ecg_id,patient_id,age,sex,height,weight,nurse,site,device,recording_date,report,"
             "scp_codes,heart_axis,infarction_stadium1,infarction_stadium2,validated_by,second_opinion,"
             "initial_autogenerated_report,validated_by_human,baseline_drift,static_noise,burst_noise,"
             "electrodes_problems,extra_beats,pacemaker,strat_fold,filename_lr,filename_hr\n")


def _write_ptbxl(tmp_path):
    scp = tmp_path / "scp.csv"
    scp.write_text(SCP, encoding="utf-8")
    db = tmp_path / "db.csv"
    rows = [
        '1391,1,59,0,,,,,,,"sinusrytm extrem vÄnster el-axel anteroseptal infarkt",'
        '"{\'IMI\': 100.0, \'ASMI\': 100.0, \'LAFB\': 100.0, \'SR\': 0.0}",,unknown,,,,,True,,,,,,,1,records100/x,records500/x',
        '4166,2,31,0,,,,,,,"sinusrhythmus inferiorer infarkt wahrscheinlich alt",'
        '"{\'IMI\': 100.0, \'ABQRS\': 0.0, \'SR\': 0.0}",ARAD,Stadium I,,,,,True,,,,,1ES,,1,records100/y,records500/y',
    ]
    db.write_text(DB_HEADER + "\n".join(rows) + "\n", encoding="utf-8")
    return str(db), str(scp)


def _ecg(ident, ecg_id, code):
    return {"id": ident, "file": "ecg/%s.png" % ident, "modality": "ECG", "normality": "abnormal",
            "findings": ["inferior myocardial infarction"], "umbrella_terms": ["myocardial infarction"],
            "verified": True, "ecg_id": ecg_id, "statement_code": code, "age": 59, "sex": "M"}


def test_ptbxl_annotation_carries_every_statement_and_the_stadium(tmp_path):
    db, scp = _write_ptbxl(tmp_path)
    dbm, scpm = en.read_ptbxl(db, scp)
    ann, co = en.ptbxl_annotation(_ecg("a", "1391", "IMI"), dbm, scpm)
    codes = {s["code"]: s for s in ann["statements"]}
    assert set(codes) == {"IMI", "ASMI", "LAFB", "SR"}
    assert codes["ASMI"]["kind"] == "diagnostic" and codes["SR"]["kind"] == "rhythm"
    # the two other diagnostic statements are the validated co-findings; the
    # rhythm statement and the film's own statement are not
    assert co == ["anteroseptal myocardial infarction", "left anterior fascicular block"]
    assert ann["source_report"].startswith("sinusrytm")
    assert ann["validated_by_human"] is True

    ann2, co2 = en.ptbxl_annotation(_ecg("b", "4166", "IMI"), dbm, scpm)
    assert co2 == []                              # ABQRS is a form statement, SR rhythm
    assert ann2["heart_axis"] == "ARAD" and ann2["axis_zh"] == "電軸極度右偏"
    assert ann2["infarction_stadium"] == "Stadium I" and ann2["stadium_zh"] == "急性期"
    assert ann2["extra_beats"] == "1ES"


def test_unknown_stadium_is_blank_not_a_value(tmp_path):
    db, scp = _write_ptbxl(tmp_path)
    dbm, scpm = en.read_ptbxl(db, scp)
    ann, _ = en.ptbxl_annotation(_ecg("a", "1391", "IMI"), dbm, scpm)
    assert ann["infarction_stadium"] == "" and ann["stadium_zh"] == ""


def test_ecg_sidecar_merge_adds_the_translation_and_per_code_zh(tmp_path):
    e = _ecg("ptbxl-IMI-1391", "1391", "IMI")
    e["annotation"] = {"statements": [{"code": "IMI", "description": "inferior myocardial infarction"},
                                      {"code": "LAFB", "description": "left anterior fascicular block"}]}
    d = tmp_path / "ecg"
    d.mkdir()
    (d / "batch_00.json").write_text(json.dumps([{
        "id": "ptbxl-IMI-1391", "language": "sv", "source_report_zh": "竇性心律，電軸極度左偏，前間壁梗塞。",
        "statements_zh": [{"code": "IMI", "zh": "下壁心肌梗塞"}, {"code": "LAFB", "zh": "左前分支阻滯"}],
        "axis_zh": "電軸極度左偏", "stadium_zh": "", "consistent_with_codes": True, "issues": ""}],
        ensure_ascii=False), encoding="utf-8")
    assert en.merge_ecg_sidecars({"ptbxl-IMI-1391": e}, str(d)) == 1
    ann = e["annotation"]
    assert ann["source_report_zh"].startswith("竇性心律")
    assert {s["code"]: s.get("zh") for s in ann["statements"]} == {"IMI": "下壁心肌梗塞", "LAFB": "左前分支阻滯"}
    assert ann["report_consistent_with_codes"] is True


def _cxr(ident):
    e = {"id": ident, "file": "cxr/%s.png" % ident, "modality": "CXR", "normality": "abnormal",
         "findings": ["pleural effusion"], "umbrella_terms": [], "verified": True,
         "attributes": ib.claim_attributes("pleural effusion")}
    return e


def _sidecar(tmp_path, ident, *, side, agreement, bbox="right", reviewed_side=None):
    d = tmp_path / "cxr"
    d.mkdir(exist_ok=True)
    (d / (ident + ".json")).write_text(json.dumps({
        "id": ident, "reviewed_by": "ai-vision-3reader", "view": "PA", "technical_quality": "ok",
        "target": {"finding": "pleural effusion", "visible": "yes", "laterality": side, "zone": "lower",
                   "size_cm": 10, "confidence": 0.8},
        "laterality_sources": {"bbox": bbox, "reader_a": side, "reader_b": side, "adjudicator": side},
        "agreement": agreement,
        "devices": [{"type": "port", "location": "left chest", "zh": "人工血管（左前胸）"}],
        "other_findings": [], "treatment_evidence": False, "first_presentation_suitable": True,
        "suitability_reason": "", "description_zh": "右側大量肋膜積水。", "label_concern": ""},
        ensure_ascii=False), encoding="utf-8")
    return str(d)


def test_cxr_side_is_recorded_as_provisional_when_everyone_agrees(tmp_path):
    e = _cxr("nih-effusion-1")
    d = _sidecar(tmp_path, "nih-effusion-1", side="right", agreement="full", bbox="right")
    merged, sided, conflicts = en.merge_cxr_sidecars({"nih-effusion-1": e}, d)
    assert (merged, sided, conflicts) == (1, 1, 0)
    assert e["attributes"]["laterality"] == "right"
    assert e["attributes"]["laterality_source"] == "bbox+ai-vision"
    assert "laterality_reviewed" not in e["attributes"]   # provisional, not a sign-off
    assert e["annotation"]["source"] == "nih+ai-vision"
    assert ib.device_names(e) == ["人工血管"]


def test_cxr_side_is_left_unset_on_conflict_or_bbox_disagreement(tmp_path):
    e1 = _cxr("nih-effusion-1")
    d = _sidecar(tmp_path, "nih-effusion-1", side="right", agreement="conflict", bbox="right")
    _, sided, conflicts = en.merge_cxr_sidecars({"nih-effusion-1": e1}, d)
    assert sided == 0 and conflicts == 1 and e1["attributes"]["laterality"] is None

    e2 = _cxr("nih-effusion-2")
    d = _sidecar(tmp_path, "nih-effusion-2", side="left", agreement="full", bbox="right")
    _, sided, _ = en.merge_cxr_sidecars({"nih-effusion-2": e2}, d)
    assert sided == 0 and e2["attributes"]["laterality"] is None   # readers vs box: not trusted


def test_a_reviewers_side_is_never_overwritten(tmp_path):
    e = _cxr("nih-effusion-1")
    e["attributes"]["laterality"] = "left"
    e["attributes"]["laterality_reviewed"] = True
    d = _sidecar(tmp_path, "nih-effusion-1", side="right", agreement="full", bbox="right")
    en.merge_cxr_sidecars({"nih-effusion-1": e}, d)
    assert e["attributes"]["laterality"] == "left"
    assert e["annotation"]["target"]["laterality"] == "right"     # the read is still recorded


def test_risk_note_names_devices_and_provisional_side(tmp_path):
    e = _cxr("nih-effusion-1")
    d = _sidecar(tmp_path, "nih-effusion-1", side="right", agreement="full", bbox="right")
    en.merge_cxr_sidecars({"nih-effusion-1": e}, d)
    text = "\n".join(ib.risk_notes(e, report_text="胸部X光：右側大量肋膜積水。"))
    assert "人工血管" in text
    assert "尚未經放射科醫師確認" in text and "右側" in text


def test_side_markers_and_initials_are_not_devices():
    e = _cxr("nih-cardiomegaly-1")
    e["annotation"] = {"devices": [
        {"type": "surgical clips (two short linear metallic clips)", "location": "left apex", "zh": "左肺尖手術夾"},
        {"type": "radiographic side marker (L) with technologist initials (external, not a medical device)",
         "location": "upper corner", "zh": "L 側別標記與技師縮寫"},
        {"type": "external marker", "location": "left shoulder", "zh": "「L」側標記（含技師縮寫）"},
        {"type": "de-identification box", "location": "corner", "zh": "去識別化黑色遮蔽框（影像偽影，非裝置）"},
        {"type": "Round radiopaque snap-type external artifact (ECG electrode snap or gown snap)",
         "location": "midline", "zh": "圓形外物影（心電圖電極扣或衣物暗扣）"},
        {"type": "central venous catheter", "location": "right IJ", "zh": "中心靜脈導管（右頸）"},
    ]}
    assert ib.device_names(e) == ["左肺尖手術夾", "中心靜脈導管"]
    text = " ".join(ib.risk_notes(e, report_text="胸部X光：心臟肥大。"))
    assert "側別標記" not in text and "技師" not in text
    assert "中心靜脈導管" in text
